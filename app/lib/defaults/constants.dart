String getLeague(int level) {
  int leagueIndex = (level - 1) ~/ 7;
  if (leagueIndex >= leagueStrings.length) {
    leagueIndex = leagueStrings.length - 1;
  }
  return leagueStrings[leagueIndex];
}

int getLeagueIndex(int level) {
  int leagueIndex = (level - 1) ~/ 7;
  if (leagueIndex >= leagueStrings.length) {
    leagueIndex = leagueStrings.length - 1;
  }
  return leagueIndex;
}

String getNextTierLevel(int level) {
  int currentLeagueIndex = (level - 1) ~/ 7;
  int nextLeagueIndex = currentLeagueIndex + 1;

  if (nextLeagueIndex >= leagueStrings.length) {
    return "You are already in the highest tier, the Mythic League.";
  } else {
    int nextTierLevel = nextLeagueIndex * 7 + 1;
    String nextTier = leagueStrings[nextLeagueIndex];
    return "You will need to reach level $nextTierLevel to reach the $nextTier.";
  }
}

